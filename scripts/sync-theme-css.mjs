// Writes the Theme Engine's Tailwind block (the shade scales and the semantic utilities: bg-primary, text-muted, border-default, ring-focus ...)
// into src/styles/main.css between the two markers. The table lives in src/theme/engine.js; a test checks that main.css matches it.
// Run: node scripts/sync-theme-css.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { tailwindBlock } from '../src/theme/engine.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(ROOT, 'src/styles/main.css');
const BEGIN = '/* theme-engine:begin (generated by scripts/sync-theme-css.mjs from src/theme/engine.js: do not edit) */';
const END = '/* theme-engine:end */';

export function syncThemeCss(css) {
  const block = `${BEGIN}\n${tailwindBlock()}\n${END}`;
  const a = css.indexOf(BEGIN), b = css.indexOf(END);
  if (a >= 0 && b > a) return css.slice(0, a) + block + css.slice(b + END.length);
  // first time: after the existing @theme inline block
  const t = css.indexOf('@theme inline {');
  const close = css.indexOf('\n}\n', t) + 3;
  return `${css.slice(0, close)}\n${block}\n${css.slice(close)}`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const before = fs.readFileSync(file, 'utf8');
  const after = syncThemeCss(before);
  if (after !== before) fs.writeFileSync(file, after);
  console.log(after === before ? 'main.css is up to date' : 'main.css updated');
}
